-- Late order reminders and complaint workflow.
-- Run after the existing schema, role, orders, fulfilment, and notification migrations.
-- The existing customer notifications table is extended compatibly; its user_id,
-- message, and order-status trigger remain intact.

alter table public.notifications add column if not exists recipient_user_id uuid references public.users(id) on delete cascade;
alter table public.notifications add column if not exists type text not null default 'order_status_updated';
alter table public.notifications add column if not exists complaint_id bigint;
update public.notifications set recipient_user_id = user_id where recipient_user_id is null;

create table if not exists public.complaints (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  raised_by uuid not null references public.users(id),
  assigned_to uuid references public.users(id),
  issue_type text not null check (issue_type in ('late_delivery','wrong_item','damaged','picker_issue','payment_refund','other')),
  severity text not null check (severity in ('low','medium','high')),
  notes text not null,
  status text not null default 'open' check (status in ('open','in_progress','resolved')),
  resolution_note text,
  orders_status_at_filing public.order_status not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);
do $$ begin
  if not exists(select 1 from pg_constraint where conname='notifications_complaint_id_fkey' and conrelid='public.notifications'::regclass) then
    alter table public.notifications add constraint notifications_complaint_id_fkey foreign key (complaint_id) references public.complaints(id) on delete cascade;
  end if;
end $$;

create table if not exists public.complaint_events (
  id bigint generated by default as identity primary key,
  complaint_id bigint not null references public.complaints(id) on delete cascade,
  actor_id uuid not null references public.users(id),
  event_type text not null check (event_type in ('created','status_changed','assigned','comment')),
  from_value text,
  to_value text,
  comment text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_order_reminders (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  sent_by uuid not null references public.users(id),
  note text,
  sent_at timestamptz not null default now()
);

create index if not exists complaints_order_created_idx on public.complaints(order_id, created_at desc);
create index if not exists complaints_status_created_idx on public.complaints(status, created_at desc);
create index if not exists complaint_events_complaint_idx on public.complaint_events(complaint_id, created_at);
create index if not exists admin_order_reminders_order_idx on public.admin_order_reminders(order_id, sent_at desc);
create unique index if not exists complaints_one_open_issue_idx on public.complaints(order_id, issue_type) where status <> 'resolved';
create index if not exists notifications_recipient_created_idx on public.notifications(recipient_user_id, created_at desc);

alter table public.complaints enable row level security;
alter table public.complaint_events enable row level security;
alter table public.admin_order_reminders enable row level security;

