create or replace function public.admin_raise_complaint(p_order_id bigint,p_issue_type text,p_severity text,p_notes text,p_assigned_to uuid default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_role text; v_order public.orders%rowtype; v_id bigint; v_recipient uuid;
begin
  select r.name::text into v_role from public.users u join public.roles r on r.id=u.role_id where u.id=auth.uid();
  if coalesce(v_role,'') <> 'super_admin' then raise exception 'ADMIN_REQUIRED'; end if;
  if p_issue_type not in ('late_delivery','wrong_item','damaged','picker_issue','payment_refund','other') then raise exception 'INVALID_ISSUE_TYPE'; end if;
  if p_severity not in ('low','medium','high') then raise exception 'INVALID_SEVERITY'; end if;
  if length(trim(coalesce(p_notes,''))) not between 1 and 500 then raise exception 'NOTES_REQUIRED'; end if;
  select * into v_order from public.orders where id=p_order_id;
  if not found then raise exception 'ORDER_NOT_FOUND'; end if;
  if p_assigned_to is null and not exists(select 1 from public.users u join public.roles r on r.id=u.role_id where r.name='store_manager') then raise exception 'NO_STORE_MANAGERS'; end if;
  if p_assigned_to is not null and not exists(select 1 from public.users u join public.roles r on r.id=u.role_id where u.id=p_assigned_to and r.name='store_manager') then raise exception 'INVALID_ASSIGNEE'; end if;
  select c.id into v_id from public.complaints c where c.order_id=p_order_id and c.issue_type=p_issue_type and c.status<>'resolved' limit 1;
  if v_id is not null then raise exception 'DUPLICATE_OPEN_COMPLAINT:%',v_id; end if;
  insert into public.complaints(order_id,raised_by,assigned_to,issue_type,severity,notes,orders_status_at_filing)
  values(p_order_id,auth.uid(),p_assigned_to,p_issue_type,p_severity,trim(p_notes),v_order.status) returning id into v_id;
  insert into public.complaint_events(complaint_id,actor_id,event_type,to_value,comment) values(v_id,auth.uid(),'created','open',trim(p_notes));
  if p_assigned_to is not null then
    v_recipient:=p_assigned_to;
    insert into public.notifications(user_id,recipient_user_id,type,title,message,body,order_id,complaint_id)
    values(v_recipient,v_recipient,'complaint_raised','Complaint raised for order #'||p_order_id,'A new '||replace(p_issue_type,'_',' ')||' complaint was assigned to you.','A new '||replace(p_issue_type,'_',' ')||' complaint was assigned to you.',p_order_id,v_id);
  else
    for v_recipient in select u.id from public.users u join public.roles r on r.id=u.role_id where r.name='store_manager' loop
      insert into public.notifications(user_id,recipient_user_id,type,title,message,body,order_id,complaint_id)
      values(v_recipient,v_recipient,'complaint_raised','Complaint raised for order #'||p_order_id,'A new '||replace(p_issue_type,'_',' ')||' complaint is open.','A new '||replace(p_issue_type,'_',' ')||' complaint is open.',p_order_id,v_id);
    end loop;
  end if;
  return v_id;
exception when unique_violation then
  select c.id into v_id from public.complaints c where c.order_id=p_order_id and c.issue_type=p_issue_type and c.status<>'resolved' limit 1;
  raise exception 'DUPLICATE_OPEN_COMPLAINT:%',coalesce(v_id,0);
end $$;

