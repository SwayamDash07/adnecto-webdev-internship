create or replace function public.admin_list_late_orders()
returns table(order_id bigint, customer_name text, total numeric, status public.order_status, created_at timestamptz, last_reminded_at timestamptz, open_complaint_id bigint)
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from public.users u join public.roles r on r.id=u.role_id where u.id=auth.uid() and r.name in ('super_admin','store_manager')) then raise exception 'COMPLAINT_ACCESS_REQUIRED'; end if;
  return query
  select o.id, coalesce(nullif(u.full_name,''), nullif(split_part(coalesce(a.email,''),'@',1),''), 'Customer'), o.total, o.status, o.created_at,
    (select max(rem.sent_at) from public.admin_order_reminders rem where rem.order_id=o.id),
    (select c.id from public.complaints c where c.order_id=o.id and c.status <> 'resolved' order by c.created_at desc limit 1)
  from public.orders o left join public.users u on u.id=o.user_id left join auth.users a on a.id=o.user_id
  where o.status in ('placed','accepted','picking') and o.created_at >= now()-interval '7 days' and o.created_at <= now()-interval '2 hours'
  order by o.created_at asc limit 5;
end $$;

create or replace function public.admin_notify_late_order(p_order_id bigint, p_note text default '')
returns timestamptz language plpgsql security definer set search_path = public as $$
declare v_order public.orders%rowtype; v_wait text; v_sent timestamptz; v_note text := left(trim(coalesce(p_note,'')),200); v_recipient record;
begin
  if not exists (select 1 from public.users u join public.roles r on r.id=u.role_id where u.id=auth.uid() and r.name='super_admin') then raise exception 'ADMIN_REQUIRED'; end if;
  select * into v_order from public.orders where id=p_order_id for update;
  if not found or v_order.status not in ('placed','accepted','picking') or v_order.created_at < now()-interval '7 days' or v_order.created_at > now()-interval '2 hours' then raise exception 'ORDER_NOT_LATE'; end if;
  if not exists(select 1 from public.users u join public.roles r on r.id=u.role_id where r.name='store_manager') then raise exception 'NO_STORE_MANAGERS'; end if;
  if exists(select 1 from public.admin_order_reminders where order_id=p_order_id and sent_at > now()-interval '30 minutes') then raise exception 'REMINDER_COOLDOWN'; end if;
  v_wait := case when extract(epoch from (now()-v_order.created_at)) < 86400 then floor(extract(epoch from (now()-v_order.created_at))/3600)::text || 'h ' || floor(mod(extract(epoch from (now()-v_order.created_at))::numeric,3600)/60)::text || 'm' else floor(extract(epoch from (now()-v_order.created_at))/86400)::text || ' days' end;
  insert into public.admin_order_reminders(order_id,sent_by,note) values(p_order_id,auth.uid(),nullif(v_note,'')) returning sent_at into v_sent;
  for v_recipient in select u.id from public.users u join public.roles r on r.id=u.role_id where r.name='store_manager' loop
    insert into public.notifications(user_id,recipient_user_id,order_id,complaint_id,type,title,message,body)
    values(v_recipient.id,v_recipient.id,p_order_id,null,'late_order_reminder','Order #'||p_order_id||' is running late',
      'Waiting '||v_wait||' · status '||replace(v_order.status::text,'_',' ')||case when v_note<>'' then ' · '||v_note else '' end,
      'Waiting '||v_wait||' · status '||replace(v_order.status::text,'_',' ')||case when v_note<>'' then ' · '||v_note else '' end);
  end loop;
  return v_sent;
end $$;

