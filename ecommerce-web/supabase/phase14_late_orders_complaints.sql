create function public.admin_list_complaints()
returns table(complaint_id bigint,order_id bigint,customer_name text,customer_email text,issue_type text,severity text,status text,assigned_to uuid,assigned_name text,orders_status_at_filing public.order_status,current_order_status public.order_status,created_at timestamptz,updated_at timestamptz,resolved_at timestamptz,raised_by uuid,raised_by_name text,notes text)
language plpgsql security definer set search_path = public as $$
begin
  if not exists(select 1 from public.users u join public.roles r on r.id=u.role_id where u.id=auth.uid() and r.name in ('super_admin','store_manager')) then raise exception 'COMPLAINT_ACCESS_REQUIRED'; end if;
  return query select c.id,c.order_id,coalesce(nullif(cu.full_name,''),ca.email,'Customer'),coalesce(ca.email,''),c.issue_type,c.severity,c.status,c.assigned_to,coalesce(nullif(ass.full_name,''),aa.email),c.orders_status_at_filing,o.status,c.created_at,c.updated_at,c.resolved_at,c.raised_by,coalesce(nullif(ru.full_name,''),ra.email,'Admin'),c.notes
  from public.complaints c join public.orders o on o.id=c.order_id left join public.users cu on cu.id=o.user_id left join auth.users ca on ca.id=o.user_id
  left join public.users ass on ass.id=c.assigned_to left join auth.users aa on aa.id=c.assigned_to left join public.users ru on ru.id=c.raised_by left join auth.users ra on ra.id=c.raised_by
  order by case c.status when 'open' then 0 when 'in_progress' then 1 else 2 end,c.created_at desc;
end $$;

create or replace function public.admin_complaint_detail(p_complaint_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_role text; v_result jsonb;
begin
  select r.name::text into v_role from public.users u join public.roles r on r.id=u.role_id where u.id=auth.uid();
  if coalesce(v_role,'') not in ('super_admin','store_manager') then raise exception 'COMPLAINT_ACCESS_REQUIRED'; end if;
  select jsonb_build_object(
    'complaint',to_jsonb(c)||jsonb_build_object('raised_by_name',coalesce(nullif(ru.full_name,''),ra.email,'Admin'),'assigned_name',coalesce(nullif(au.full_name,''),aa.email)),
    'order',jsonb_build_object('order_id',o.id,'status',o.status,'created_at',o.created_at,'customer_name',coalesce(nullif(cu.full_name,''),ca.email,'Customer'),'email',coalesce(ca.email,''),'phone',cu.phone,'address',concat_ws(', ',ad.line1,ad.city,ad.postal_code),'delivery_slot',o.delivery_slot,'total',o.total,'subtotal',coalesce(items.subtotal,0),'discount',null,'payment_status',pay.status,'items',coalesce(items.rows,'[]'::jsonb)),
    'events',coalesce(ev.rows,'[]'::jsonb),'order_history',coalesce(hist.rows,'[]'::jsonb))
  into v_result from public.complaints c join public.orders o on o.id=c.order_id left join public.users cu on cu.id=o.user_id left join auth.users ca on ca.id=o.user_id left join public.addresses ad on ad.id=o.address_id
  left join public.users ru on ru.id=c.raised_by left join auth.users ra on ra.id=c.raised_by left join public.users au on au.id=c.assigned_to left join auth.users aa on aa.id=c.assigned_to
  left join lateral (select sum(oi.quantity*oi.unit_price) subtotal,jsonb_agg(jsonb_build_object('name',p.name,'quantity',oi.quantity,'price',oi.unit_price) order by oi.id) rows from public.order_items oi join public.products p on p.id=oi.product_id where oi.order_id=o.id) items on true
  left join lateral (select coalesce(jsonb_agg(jsonb_build_object('id',e.id,'actor_name',coalesce(nullif(u.full_name,''),a.email,'Staff'),'event_type',e.event_type,'from_value',e.from_value,'to_value',e.to_value,'comment',e.comment,'created_at',e.created_at) order by e.created_at),'[]'::jsonb) rows from public.complaint_events e left join public.users u on u.id=e.actor_id left join auth.users a on a.id=e.actor_id where e.complaint_id=c.id) ev on true
  left join lateral (select coalesce(jsonb_agg(jsonb_build_object('created_at',l.created_at,'from_value',coalesce(l.payload->>'from',l.payload->'old'->>'status'),'to_value',coalesce(l.payload->>'to',l.payload->>'status',l.payload->'new'->>'status'),'actor_id',l.actor_id,'actor_name',coalesce(nullif(lu.full_name,''),la.email,'Staff')) order by l.created_at),'[]'::jsonb) rows from public.audit_logs l left join public.users lu on lu.id=l.actor_id left join auth.users la on la.id=l.actor_id where l.table_name='orders' and l.row_id=o.id::text and l.action in ('UPDATE','order_status_updated','fulfilment_status_updated')) hist on true
  left join lateral (select string_agg(distinct p.status, ', ' order by p.status) status from public.payments p where p.order_id=o.id) pay on true
  where c.id=p_complaint_id;
  if v_result is null then raise exception 'COMPLAINT_NOT_FOUND'; end if;
  return v_result;
end $$;

create or replace function public.admin_update_complaint(p_complaint_id bigint,p_status text default null,p_assigned_to uuid default null,p_update_assignment boolean default false,p_comment text default null,p_resolution_note text default null)
returns void language plpgsql security definer set search_path = public as $$
declare v_role text; v_c public.complaints%rowtype; v_recipient uuid; v_changed boolean := false;
begin
  select r.name::text into v_role from public.users u join public.roles r on r.id=u.role_id where u.id=auth.uid();
  if coalesce(v_role,'') <> 'store_manager' then raise exception 'MANAGER_REQUIRED'; end if;
  select * into v_c from public.complaints where id=p_complaint_id for update;
  if not found then raise exception 'COMPLAINT_NOT_FOUND'; end if;
  if p_status is not null and p_status not in ('open','in_progress','resolved') then raise exception 'INVALID_STATUS'; end if;
  if p_update_assignment and p_assigned_to is not null and not exists(select 1 from public.users u join public.roles r on r.id=u.role_id where u.id=p_assigned_to and r.name='store_manager') then raise exception 'INVALID_ASSIGNEE'; end if;
  if p_status='resolved' and length(trim(coalesce(p_resolution_note,'')))=0 then raise exception 'RESOLUTION_NOTE_REQUIRED'; end if;
  if p_update_assignment and p_assigned_to is distinct from v_c.assigned_to then
    update public.complaints set assigned_to=p_assigned_to where id=p_complaint_id;
    insert into public.complaint_events(complaint_id,actor_id,event_type,from_value,to_value) values(p_complaint_id,auth.uid(),'assigned',v_c.assigned_to::text,p_assigned_to::text);
    v_changed:=true;
  end if;
  if p_status is not null and p_status is distinct from v_c.status then
    update public.complaints set status=p_status,resolution_note=case when p_status='resolved' then trim(p_resolution_note) else resolution_note end,resolved_at=case when p_status='resolved' then now() else null end where id=p_complaint_id;
    insert into public.complaint_events(complaint_id,actor_id,event_type,from_value,to_value,comment) values(p_complaint_id,auth.uid(),'status_changed',v_c.status,p_status,case when p_status='resolved' then trim(p_resolution_note) else null end);
    v_changed:=true;
  elsif p_status='resolved' and p_status=v_c.status and coalesce(trim(v_c.resolution_note),'')='' then
    update public.complaints set resolution_note=trim(p_resolution_note),resolved_at=coalesce(resolved_at,now()) where id=p_complaint_id;
    insert into public.complaint_events(complaint_id,actor_id,event_type,comment) values(p_complaint_id,auth.uid(),'comment','Resolution note: '||trim(p_resolution_note));
    v_changed:=true;
  end if;
  if nullif(trim(coalesce(p_comment,'')),'') is not null then
    insert into public.complaint_events(complaint_id,actor_id,event_type,comment) values(p_complaint_id,auth.uid(),'comment',left(trim(p_comment),1000));
    v_changed:=true;
  end if;
  if v_changed then update public.complaints set updated_at=now() where id=p_complaint_id; end if;
  v_recipient:=v_c.raised_by;
  if v_changed then
    insert into public.notifications(user_id,recipient_user_id,type,title,message,body,order_id,complaint_id)
    values(v_recipient,v_recipient,'complaint_updated','Complaint updated for order #'||v_c.order_id,'Complaint #'||p_complaint_id||' has a new update.','Complaint #'||p_complaint_id||' has a new update.',v_c.order_id,p_complaint_id);
  end if;
end $$;

