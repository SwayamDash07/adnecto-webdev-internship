-- Admin to staff messages with recipient-scoped read, acknowledgement and completion.
create table if not exists public.admin_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.users(id) on delete cascade,
  message_type text not null check (message_type in ('alert','issue','announcement')),
  title text not null,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_message_recipients (
  id bigint generated by default as identity primary key,
  message_id bigint not null references public.admin_messages(id) on delete cascade,
  recipient_id uuid not null references public.users(id) on delete cascade,
  read_at timestamptz,
  acknowledged_at timestamptz,
  done_at timestamptz,
  done_note text,
  reminder_at timestamptz,
  unique(message_id, recipient_id),
  constraint admin_message_done_note_length check (done_note is null or char_length(done_note) <= 200)
);
alter table public.admin_message_recipients add column if not exists done_at timestamptz;
alter table public.admin_message_recipients add column if not exists done_note text;
alter table public.admin_message_recipients add column if not exists reminder_at timestamptz;
do $$ begin
 if not exists(select 1 from pg_constraint where conname='admin_message_done_note_length' and conrelid='public.admin_message_recipients'::regclass) then
   alter table public.admin_message_recipients add constraint admin_message_done_note_length check(done_note is null or char_length(done_note)<=200);
 end if;
end $$;

alter table public.admin_messages enable row level security;
alter table public.admin_message_recipients enable row level security;
create or replace function public.is_own_admin_message_recipient(p_message_id bigint)
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.admin_message_recipients r where r.message_id=p_message_id and r.recipient_id=auth.uid())
$$;
create or replace function public.owns_admin_staff_message(p_message_id bigint)
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.admin_messages m where m.id=p_message_id and m.sender_id=auth.uid())
$$;
revoke all on function public.is_own_admin_message_recipient(bigint),public.owns_admin_staff_message(bigint) from public,anon;
grant execute on function public.is_own_admin_message_recipient(bigint),public.owns_admin_staff_message(bigint) to authenticated;
drop policy if exists "staff read own admin messages" on public.admin_message_recipients;
create policy "staff read own admin messages" on public.admin_message_recipients for select to authenticated using(recipient_id=auth.uid());
drop policy if exists "admin reads sent message recipients" on public.admin_message_recipients;
create policy "admin reads sent message recipients" on public.admin_message_recipients for select to authenticated using(public.owns_admin_staff_message(message_id));
drop policy if exists "admin read sent messages" on public.admin_messages;
create policy "admin read sent messages" on public.admin_messages for select to authenticated using(public.current_role()='super_admin');
drop policy if exists "recipient reads message content" on public.admin_messages;
create policy "recipient reads message content" on public.admin_messages for select to authenticated using(public.is_own_admin_message_recipient(id));
revoke all on public.admin_message_recipients from anon, authenticated;
grant select on public.admin_message_recipients, public.admin_messages to authenticated;

create or replace function public.staff_list_admin_messages()
returns table(message_id bigint, recipient_row_id bigint, sender_id uuid, sender_name text, message_type text, title text, body text, created_at timestamptz, read_at timestamptz, acknowledged_at timestamptz, done_at timestamptz, done_note text)
language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
 return query select m.id,r.id,m.sender_id,coalesce(u.full_name,'Administrator')::text,m.message_type,m.title,m.body,m.created_at,r.read_at,r.acknowledged_at,r.done_at,r.done_note
 from public.admin_message_recipients r join public.admin_messages m on m.id=r.message_id left join public.users u on u.id=m.sender_id
 where r.recipient_id=auth.uid() order by m.created_at desc;
end $$;

create or replace function public.staff_update_admin_message(p_recipient_row_id bigint,p_action text,p_done_note text default null)
returns public.admin_message_recipients language plpgsql security definer set search_path=public as $$
declare r public.admin_message_recipients%rowtype; m public.admin_messages%rowtype;
begin
 if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
 select * into r from public.admin_message_recipients where id=p_recipient_row_id and recipient_id=auth.uid() for update;
 if not found then raise exception 'MESSAGE_NOT_FOUND' using errcode='42501'; end if;
 select * into m from public.admin_messages where id=r.message_id;
 if p_action='read' then update public.admin_message_recipients set read_at=coalesce(read_at,now()) where id=r.id returning * into r;
 elsif p_action='acknowledge' then
   if m.message_type<>'announcement' then raise exception 'ACKNOWLEDGEMENT_NOT_ALLOWED'; end if;
   update public.admin_message_recipients set read_at=coalesce(read_at,now()),acknowledged_at=coalesce(acknowledged_at,now()) where id=r.id returning * into r;
 elsif p_action='done' then
   if m.message_type not in ('alert','issue') then raise exception 'MESSAGE_CANNOT_BE_MARKED_DONE'; end if;
   if r.done_at is not null then raise exception 'MESSAGE_ALREADY_DONE'; end if;
   if char_length(coalesce(p_done_note,''))>200 then raise exception 'DONE_NOTE_TOO_LONG'; end if;
   update public.admin_message_recipients set read_at=coalesce(read_at,now()),acknowledged_at=coalesce(acknowledged_at,now()),done_at=now(),done_note=nullif(trim(coalesce(p_done_note,'')),'') where id=r.id returning * into r;
 elsif p_action='undo' then
   if r.done_at is null or now()>r.done_at+interval '10 seconds' then raise exception 'UNDO_EXPIRED'; end if;
   update public.admin_message_recipients set done_at=null,done_note=null where id=r.id returning * into r;
 else raise exception 'INVALID_ACTION'; end if;
 return r;
end $$;
revoke all on function public.staff_list_admin_messages(),public.staff_update_admin_message(bigint,text,text) from public,anon;
grant execute on function public.staff_list_admin_messages(),public.staff_update_admin_message(bigint,text,text) to authenticated;
create or replace function public.staff_mark_all_admin_messages_read()
returns integer language plpgsql security definer set search_path=public as $$
declare changed integer;
begin
 if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
 update public.admin_message_recipients set read_at=now() where recipient_id=auth.uid() and read_at is null;
 get diagnostics changed=row_count;
 return changed;
end $$;
revoke all on function public.staff_mark_all_admin_messages_read() from public,anon;
grant execute on function public.staff_mark_all_admin_messages_read() to authenticated;

create or replace function public.admin_send_staff_message(p_type text,p_title text,p_body text,p_recipient_ids uuid[])
returns bigint language plpgsql security definer set search_path=public as $$
declare mid bigint;
begin
 if public.current_role()<>'super_admin' then raise exception 'FORBIDDEN' using errcode='42501'; end if;
 if p_type not in ('alert','issue','announcement') or nullif(trim(p_title),'') is null or nullif(trim(p_body),'') is null or coalesce(cardinality(p_recipient_ids),0)=0 then raise exception 'INVALID_MESSAGE'; end if;
 insert into public.admin_messages(sender_id,message_type,title,body) values(auth.uid(),p_type,trim(p_title),trim(p_body)) returning id into mid;
 insert into public.admin_message_recipients(message_id,recipient_id)
 select mid,u.id from public.users u join public.roles ro on ro.id=u.role_id where u.id=any(p_recipient_ids) and ro.name::text in ('store_manager','picker','customer_support');
 if not found then raise exception 'NO_VALID_RECIPIENTS'; end if;
 return mid;
end $$;
create or replace function public.admin_list_sent_staff_messages()
returns table(message_id bigint,message_type text,title text,body text,created_at timestamptz,recipient_count bigint,read_count bigint,done_count bigint,acknowledged_count bigint)
language plpgsql security definer set search_path=public as $$
begin
 if public.current_role()<>'super_admin' then raise exception 'FORBIDDEN' using errcode='42501'; end if;
 return query select m.id,m.message_type,m.title,m.body,m.created_at,count(r.id),count(r.id) filter(where r.read_at is not null),count(r.id) filter(where r.done_at is not null),count(r.id) filter(where r.acknowledged_at is not null)
 from public.admin_messages m left join public.admin_message_recipients r on r.message_id=m.id where m.sender_id=auth.uid() group by m.id order by m.created_at desc;
end $$;
create or replace function public.admin_list_staff_message_targets()
returns table(user_id uuid,full_name text,role_name text)
language plpgsql security definer set search_path=public as $$
begin
 if public.current_role()<>'super_admin' then raise exception 'FORBIDDEN' using errcode='42501'; end if;
 return query select u.id,coalesce(u.full_name,'Staff')::text,ro.name::text from public.users u join public.roles ro on ro.id=u.role_id where ro.name::text<>'super_admin' order by u.full_name;
end $$;
create or replace function public.admin_remind_staff_message(p_message_id bigint)
returns integer language plpgsql security definer set search_path=public as $$
declare r record; total integer:=0;
begin
 if public.current_role()<>'super_admin' or not exists(select 1 from public.admin_messages where id=p_message_id and sender_id=auth.uid()) then raise exception 'FORBIDDEN' using errcode='42501'; end if;
 for r in select mr.id,mr.recipient_id,m.title from public.admin_message_recipients mr join public.admin_messages m on m.id=mr.message_id where m.id=p_message_id and ((m.message_type='announcement' and mr.acknowledged_at is null) or (m.message_type in ('alert','issue') and mr.done_at is null)) and (mr.reminder_at is null or mr.reminder_at<now()-interval '30 minutes') loop
   update public.admin_message_recipients set reminder_at=now() where id=r.id;
   insert into public.notifications(user_id,recipient_user_id,type,title,message,body) values(r.recipient_id,r.recipient_id,'admin_message_reminder','Reminder: '||r.title,'Please review this staff message.','Please review this staff message.');
   total:=total+1;
 end loop;
 return total;
end $$;
create or replace function public.admin_staff_message_recipients(p_message_id bigint)
returns table(recipient_id uuid,full_name text,role_name text,read_at timestamptz,done_at timestamptz,acknowledged_at timestamptz,done_note text)
language plpgsql security definer set search_path=public as $$
begin
 if public.current_role()<>'super_admin' or not exists(select 1 from public.admin_messages where id=p_message_id and sender_id=auth.uid()) then raise exception 'FORBIDDEN' using errcode='42501'; end if;
 return query select r.recipient_id,coalesce(u.full_name,'Staff')::text,ro.name::text,r.read_at,r.done_at,r.acknowledged_at,r.done_note from public.admin_message_recipients r join public.users u on u.id=r.recipient_id left join public.roles ro on ro.id=u.role_id where r.message_id=p_message_id order by u.full_name;
end $$;
revoke all on function public.admin_send_staff_message(text,text,text,uuid[]),public.admin_list_sent_staff_messages(),public.admin_list_staff_message_targets(),public.admin_remind_staff_message(bigint),public.admin_staff_message_recipients(bigint) from public,anon;
grant execute on function public.admin_send_staff_message(text,text,text,uuid[]),public.admin_list_sent_staff_messages(),public.admin_list_staff_message_targets(),public.admin_remind_staff_message(bigint),public.admin_staff_message_recipients(bigint) to authenticated;

create or replace function public.notify_admin_staff_message_done() returns trigger language plpgsql security definer set search_path=public as $$
declare m public.admin_messages%rowtype; actor_name text; admin_id uuid; done_count integer; total_count integer; n_id bigint;
begin
 if old.done_at is null and new.done_at is not null then
   select * into m from public.admin_messages where id=new.message_id;
   select coalesce(full_name,'Staff') into actor_name from public.users where id=new.recipient_id;
   select count(*) filter(where done_at is not null),count(*) into done_count,total_count from public.admin_message_recipients where message_id=new.message_id;
   for admin_id in select u.id from public.users u join public.roles ro on ro.id=u.role_id where ro.name::text='super_admin' loop
     select id into n_id from public.notifications where user_id=admin_id and type='admin_message_done' and created_at>now()-interval '5 minutes' and position('"admin_message_id":'||new.message_id::text in body)>0 order by created_at desc limit 1;
     if n_id is null then
       insert into public.notifications(user_id,recipient_user_id,type,title,message,body) values(admin_id,admin_id,'admin_message_done',actor_name||' marked '||quote_literal(m.title)||' as done',case when done_count=total_count then done_count||' of '||total_count||' recipients marked '||quote_literal(m.title)||' as done' else actor_name||' marked '||quote_literal(m.title)||' as done' end,jsonb_build_object('admin_message_id',new.message_id,'done_count',done_count,'recipient_count',total_count)::text) returning id into n_id;
     else
       update public.notifications set title=done_count||' of '||total_count||' recipients marked '||quote_literal(m.title)||' as done',message=done_count||' of '||total_count||' recipients marked '||quote_literal(m.title)||' as done',body=jsonb_build_object('admin_message_id',new.message_id,'done_count',done_count,'recipient_count',total_count)::text where id=n_id;
     end if;
     n_id:=null;
   end loop;
 end if;
 return new;
end $$;
drop trigger if exists admin_message_done_notification on public.admin_message_recipients;
create trigger admin_message_done_notification after update of done_at on public.admin_message_recipients for each row execute function public.notify_admin_staff_message_done();

